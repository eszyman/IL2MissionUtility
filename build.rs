//! Embed `assets/models/*.png`, sharing one copy of identical bytes so
//! placeholder duplicates do not bloat the binary.

use std::collections::BTreeMap;
use std::fs;
use std::hash::{Hash, Hasher};
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=assets/models");
    println!("cargo:rerun-if-changed=assets/clouds");

    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let models_dir = manifest.join("assets/models");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let dest = out_dir.join("model_images.rs");

    let placeholder_src = models_dir.join("placeholder.png");
    let placeholder_bytes = fs::read(&placeholder_src).unwrap_or_default();
    fs::write(out_dir.join("placeholder.png"), &placeholder_bytes)
        .expect("write placeholder.png to OUT_DIR");

    let mut hash_to_file: BTreeMap<u64, String> = BTreeMap::new();
    let mut id_to_hash: BTreeMap<String, u64> = BTreeMap::new();

    if models_dir.is_dir() {
        let mut entries: Vec<fs::DirEntry> = fs::read_dir(&models_dir)
            .expect("read assets/models")
            .filter_map(|e| e.ok())
            .collect();
        entries.sort_by_key(|e| e.file_name());
        for entry in entries {
            let path = entry.path();
            if path
                .extension()
                .and_then(|e| e.to_str())
                .map(|e| e.eq_ignore_ascii_case("png"))
                != Some(true)
            {
                continue;
            }
            let stem = path
                .file_stem()
                .and_then(|s| s.to_str())
                .unwrap_or("")
                .to_ascii_lowercase();
            if stem.is_empty() || stem == "placeholder" {
                continue;
            }
            let Ok(bytes) = fs::read(&path) else {
                continue;
            };
            let hash = file_hash(&bytes);
            hash_to_file.entry(hash).or_insert_with(|| {
                let name = format!("{hash:016x}.png");
                fs::write(out_dir.join(&name), &bytes).expect("write unique model png");
                name
            });
            id_to_hash.insert(stem, hash);
        }
    }

    let mut src = String::from(
        r#"// @generated by build.rs — do not edit.
pub const PLACEHOLDER_PNG: &[u8] = include_bytes!("placeholder.png");

"#,
    );

    let mut const_names: BTreeMap<u64, String> = BTreeMap::new();
    for (i, (hash, file)) in hash_to_file.iter().enumerate() {
        let name = format!("IMG_{i}");
        src.push_str(&format!(
            "const {name}: &[u8] = include_bytes!(\"{file}\");\n"
        ));
        const_names.insert(*hash, name);
    }

    src.push_str(
        r#"
pub fn model_png(id: &str) -> &'static [u8] {
    match id {
"#,
    );
    for (id, hash) in &id_to_hash {
        let cname = const_names.get(hash).expect("hash const");
        src.push_str(&format!("        \"{id}\" => {cname},\n"));
    }
    src.push_str(
        r#"        _ => PLACEHOLDER_PNG,
    }
}
"#,
    );

    fs::write(&dest, src).unwrap_or_else(|err| {
        panic!("could not write {}: {err}", dest.display());
    });
    write_cloud_hours(&manifest, &out_dir);
}

/// One picture per cloud type, plus an hourly day set and one night frame
/// when `tools/mapcapture/clouds.py` has written them.
fn write_cloud_hours(manifest: &std::path::Path, out_dir: &std::path::Path) {
    let root = manifest.join("assets/clouds");
    let mut presets: Vec<String> = fs::read_dir(&root)
        .expect("read assets/clouds")
        .filter_map(|entry| entry.ok())
        .map(|entry| entry.path())
        .filter(|path| {
            path.extension()
                .and_then(|ext| ext.to_str())
                .is_some_and(|ext| ext.eq_ignore_ascii_case("jpg"))
                && path.file_name().and_then(|name| name.to_str()) != Some("night.jpg")
        })
        .filter_map(|path| {
            path.file_stem()
                .and_then(|stem| stem.to_str())
                .map(str::to_string)
        })
        .collect();
    presets.sort();
    if presets.len() != 50 || presets.first().map(String::as_str) != Some("00_clear_00") {
        panic!(
            "assets/clouds needs the 50 editor presets, found {}",
            presets.len()
        );
    }

    let include = |path: PathBuf| {
        let text = path.to_string_lossy().replace('\\', "/");
        format!("include_bytes!(r\"{text}\")")
    };

    let mut src = String::from("// @generated by build.rs — do not edit.\n\n");
    src.push_str("fn fallback(index: usize) -> &'static [u8] {\n    match index {\n");
    for (index, name) in presets.iter().enumerate() {
        let path = root.join(format!("{name}.jpg"));
        src.push_str(&format!("        {index} => {},\n", include(path)));
    }
    let light = root.join("01_light_00.jpg");
    src.push_str(&format!(
        "        _ => {},\n    }}\n}}\n\n",
        include(light.clone())
    ));

    let night = root.join("night.jpg");
    src.push_str("fn night_frame(index: usize) -> &'static [u8] {\n");
    if night.is_file() {
        src.push_str(&format!(
            "    let _ = index;\n    {}\n}}\n\n",
            include(night)
        ));
    } else {
        src.push_str("    fallback(index)\n}\n\n");
    }

    src.push_str(
        "fn day_frame(hour: u32, index: usize) -> &'static [u8] {\n    match (hour, index) {\n",
    );
    for hour in 7u32..=19 {
        let dir = root.join(format!("h{hour:02}"));
        if !dir.is_dir() {
            continue;
        }
        for (index, name) in presets.iter().enumerate() {
            let path = dir.join(format!("{name}.jpg"));
            if path.is_file() {
                src.push_str(&format!(
                    "        ({hour}, {index}) => {},\n",
                    include(path)
                ));
            }
        }
    }
    src.push_str("        _ => fallback(index),\n    }\n}\n\n");
    src.push_str(
        "pub fn jpeg(index: usize, hour: u32) -> &'static [u8] {\n    \
         if is_night_hour(hour) {\n        \
         night_frame(index)\n    \
         } else {\n        \
         day_frame(hour, index)\n    \
         }\n}\n",
    );

    let dest = out_dir.join("cloud_hours.rs");
    fs::write(&dest, src).unwrap_or_else(|err| {
        panic!("could not write {}: {err}", dest.display());
    });
}

fn file_hash(bytes: &[u8]) -> u64 {
    let mut hasher = std::collections::hash_map::DefaultHasher::new();
    bytes.hash(&mut hasher);
    hasher.finish()
}
